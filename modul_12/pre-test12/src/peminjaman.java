public class peminjaman {
    String anggota;
    String judulBuku;
    int tanggal;
    int bulan;
    int tahun;

    public peminjaman(String anggota, String judulBuku, int tanggal, int bulan, int tahun) {
        this.anggota = anggota;
        this.judulBuku = judulBuku;
        this.tanggal = tanggal;
        this.bulan = bulan;
        this.tahun = tahun;
    }

}
